'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const data=require('../data/papers.json');
const {matches,text}=require('../assets/app.js');
const all=data.papers.map(p=>({...p,searchText:text(JSON.stringify(p)).toLowerCase()}));
const byId=id=>all.find(p=>p.id===id);
const audit=data.reportCitationAudit;
assert.equal(audit.updated,data.updated);
assert(audit.policy.includes('不自动证明'));
for(const e of audit.links){
 assert(audit.reports.some(r=>r.id===e.report));
 assert(e.sources.length&&e.sources.every(s=>/^https:\/\/arxiv\.org\/html\/[^#]+#/.test(s.url)));
 const p=byId(e.paper);
 assert(p.reportEvidence.some(x=>x.report===e.report&&x.kind===e.kind));
 const row=p.profile.fields.find(f=>f.key==='reportContext');
 assert(row.value.includes(e.value));
 assert(e.sources.every(s=>row.sources.some(x=>x.url===s.url)));
}
const query=facets=>all.filter(p=>matches(p,{q:'',category:'',quick:'all',year:'',tags:[],facets}));
assert.deepEqual(query({reportEvidence:['ReportAdopted']}).map(p=>p.id).sort(),['deepseek-harness','tml-on-policy-distillation']);
assert.deepEqual(query({reportEvidence:['ReportCompared']}).map(p=>p.id),['deepseek-harness']);
assert.equal(query({reportEvidence:['ReportAdopted'],type:['blog']})[0].id,'tml-on-policy-distillation');
assert.equal(query({reportEvidence:['ReportAdopted'],type:['repository']})[0].id,'deepseek-harness');
assert.equal(query({reportEvidence:['ReportCited']}).length,0);
assert(!byId('tml-on-policy-distillation').attributions.some(a=>/deepseek|glm/i.test(a.tag)),'Usage must not create false authorship.');
for(const id of ['2505.22954','2507.19457'])if(byId(id))assert(!byId(id).tags.includes('ReportAdopted'),'Do not infer adoption for related RSI work.');
const batch=query({}).filter(p=>p.tags.includes('Update20261028'));
assert.equal(batch.length,17);
assert.equal(batch.filter(p=>p.date>='2026-10-20'&&['paper','survey'].includes(p.contentType)).length,7);
for(const [type,n] of Object.entries({paper:11,report:2,survey:1,blog:2,repository:1}))assert.equal(batch.filter(p=>p.contentType===type).length,n);
assert.equal(byId('deepseek-harness').dateLabel,'仓库核对日期');
assert.equal(byId('tml-on-policy-distillation').date,'2025-10-27');
assert.equal(byId('2602.15763').date,'2026-02-17');
assert(fs.existsSync('data/update-2026-10-28.md'));
const app=fs.readFileSync('assets/app.js','utf8'),index=fs.readFileSync('index.html','utf8');
assert(app.includes('literature-20261028')&&index.includes('literature-20261028'));
assert(index.includes('?reportEvidence=ReportAdopted'));
console.log('Passed: scoped report-use evidence, independent authorship, source propagation, resource filters, new/earlier publication dates and October 28 inventory.');
